"""Regression tests for the *running* app.py's QUALITY-BATCH-DIAG behavior.

No network; upstream responses are generated by httpx.MockTransport.
"""
import json
import logging
import sqlite3

import httpx
from fastapi.testclient import TestClient

import app


def body(rows):
    return {
        "model": "deepseek-flash",
        "messages": [
            {"role": "system", "content": "豆包数据质量审核器"},
            {"role": "user", "content": "批量输入：\n<reviews>\n" +
                json.dumps(rows, ensure_ascii=False) + "\n</reviews>"},
        ],
        "response_format": {"type": "json_object"},
        "max_tokens": 6000,
    }


def review(identifier):
    return {
        "batch_item_id": f"comment:{identifier}",
        "source_comment_id": str(identifier),
        "content": f"豆包的图片生成第 {identifier} 次失败了",
        "rating": 2,
        "review_date": "2026-11-02",
        "source": "应用宝",
        "app_version": None,
    }


def good_reply(request):
    request_body = json.loads(request.content)
    reviews = app.extract_tagged_json(app.get_user_message(request_body), "reviews")
    result = {"results": [
        {"batch_item_id": row["batch_item_id"], "is_valid": True, "invalid_reason": None}
        for row in reviews
    ]}
    return httpx.Response(200, json={
        "model": "deepseek-flash", "choices": [{
            "finish_reason": "stop", "message": {
                "role": "assistant", "content": json.dumps(result, ensure_ascii=False)
            }
        }],
        "usage": {"total_tokens": 12}
    })


def test_original_diagnostic_on_uncached_full_batch_and_not_on_hit(tmp_path, monkeypatch, caplog):
    monkeypatch.setenv("REVIEW_CACHE_ENABLED", "0")
    calls = []
    def mock(request):
        calls.append(request)
        return good_reply(request)
    instance = app.create_app(
        db_path=tmp_path / "cache.sqlite3", api_key="fake-key",
        transport=httpx.MockTransport(mock),
    )
    payload = body([review(1), review(2), review(3)])
    with TestClient(instance) as client, caplog.at_level(logging.WARNING, logger="uvicorn.error"):
        first = client.post("/chat/completions", headers={"X-Cache-Stage": "quality-batch"}, json=payload)
        second = client.post("/chat/completions", headers={"X-Cache-Stage": "quality-batch"}, json=payload)
    assert first.status_code == 200 and second.status_code == 200
    assert first.content == second.content
    assert first.headers["X-AI-Cache"] == "MISS"
    assert second.headers["X-AI-Cache"] == "HIT"
    assert len(calls) == 1
    diag = [record.message for record in caplog.records if "QUALITY-BATCH-DIAG" in record.message]
    assert len(diag) == 1
    assert "expected_count=3" in diag[0]
    assert "result_count=3" in diag[0]
    assert "ids_match=True" in diag[0]
    assert "usage={'total_tokens': 12}" in diag[0]


def test_partial_request_restores_original_diagnostic_for_only_missing_comment(tmp_path, monkeypatch, caplog):
    monkeypatch.setenv("REVIEW_CACHE_ENABLED", "1")
    calls = []
    def mock(request):
        calls.append(json.loads(request.content))
        return good_reply(request)
    instance = app.create_app(
        db_path=tmp_path / "cache.sqlite3", api_key="fake-key",
        transport=httpx.MockTransport(mock),
    )
    with TestClient(instance) as client, caplog.at_level(logging.WARNING, logger="uvicorn.error"):
        a = client.post("/chat/completions", headers={"X-Cache-Stage": "quality-batch"}, json=body([review(1)]))
        assert a.status_code == 200
        b = client.post("/chat/completions", headers={"X-Cache-Stage": "quality-batch"}, json=body([review(1),review(2)]))
        assert b.status_code == 200
        assert b.headers["X-AI-Cache"] == "PARTIAL"
    assert len(calls) == 2
    assert [r["batch_item_id"] for r in app.extract_tagged_json(app.get_user_message(calls[1]), "reviews")] == ["comment:2"]
    final = app.parse_response_json(b.json())
    assert {r["batch_item_id"] for r in final["results"]} == {"comment:1", "comment:2"}
    diags = [record.message for record in caplog.records if "QUALITY-BATCH-DIAG" in record.message]
    assert len(diags) == 2
    assert "expected_count=1" in diags[-1]
    assert "result_count=1" in diags[-1]
    assert "ids_match=True" in diags[-1]


def test_diagnostic_of_invalid_response_then_refuse_cache(tmp_path, monkeypatch, caplog):
    monkeypatch.setenv("REVIEW_CACHE_ENABLED", "1")
    calls = []
    def bad(request):
        calls.append(request)
        rows = app.extract_tagged_json(app.get_user_message(json.loads(request.content)), "reviews")
        result = {"results": [{
            "batch_item_id": rows[0]["batch_item_id"],
            "is_valid": False,
            "invalid_reason": "generic_praise_no_product_information"
        }]}
        return httpx.Response(200, json={"choices": [{"finish_reason": "stop", "message": {"role": "assistant", "content": json.dumps(result)}}]})
    instance = app.create_app(db_path=tmp_path / "cache.sqlite3", api_key="fake-key", transport=httpx.MockTransport(bad))
    with TestClient(instance) as client, caplog.at_level(logging.WARNING, logger="uvicorn.error"):
        r = client.post("/chat/completions", headers={"X-Cache-Stage": "quality-batch"}, json=body([review(1)]))
    assert r.status_code == 502
    assert len(calls) == 1
    assert any("generic_praise_no_product_information" in rec.message for rec in caplog.records if "QUALITY-BATCH-DIAG" in rec.message)
    with sqlite3.connect(tmp_path / "cache.sqlite3") as db:
        assert db.execute("SELECT count(*) FROM ai_cache").fetchone()[0] == 0
        assert db.execute("SELECT count(*) FROM ai_review_cache").fetchone()[0] == 0


def test_legacy_request_hash_and_default_opt_in(tmp_path, monkeypatch):
    monkeypatch.delenv("REVIEW_CACHE_ENABLED", raising=False)
    assert app.is_review_cache_enabled() is False
    payload = body([review(1)])
    import hashlib
    previous_key = hashlib.sha256(app.canonical_json({
        "namespace": "issue-v2", "stage": "quality-batch", "request": payload
    }).encode("utf-8")).hexdigest()
    assert app.request_hash(payload, "issue-v2", "quality-batch", "legacy") == previous_key
